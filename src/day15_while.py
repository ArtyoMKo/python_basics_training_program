#%% code interactive: 9; 6; դուրս
# Առաջադրանք 1, 2, 3 — հավաքել գնահատականներ մինչև «դուրս»

class_grades = []

while True:
    answer = input("Գնահատական (կամ «դուրս»)՝ ")

    if answer == "դուրս":
        break

    if not answer.isdigit():
        print("Դա թիվ չէ։")
        continue

    class_grades.append(int(answer))

print(f"Հավաքվեց {len(class_grades)} գնահատական")

